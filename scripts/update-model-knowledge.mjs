#!/usr/bin/env node
/**
 * Refreshes the model catalog the engine ships (sidecar/src/model-knowledge.data.ts): the public
 * OpenRouter list, trimmed to the OpenAI, Anthropic, Google and xAI models and to the fields the
 * picker judges a model by. A provider's own list (an API key's /models) names its models and
 * little else; the engine fills in context, reply length, JSON support, prices and the quality
 * score from this snapshot, so every model gets a verdict without a call to a third party at run
 * time. Run before a release: `bun run update:models`.
 */
import { writeFileSync } from "node:fs";

const PREFIXES = ["openai/", "anthropic/", "google/", "x-ai/"];
const KEPT_PARAMETERS = new Set(["response_format", "structured_outputs", "tools"]);
const OUT = new URL("../sidecar/src/model-knowledge.data.ts", import.meta.url);

const res = await fetch("https://openrouter.ai/api/v1/models", { signal: AbortSignal.timeout(30_000) });
if (!res.ok) throw new Error(`OpenRouter answered HTTP ${res.status}`);
const { data } = await res.json();
const models = data
  .filter((m) => PREFIXES.some((p) => m.id.startsWith(p)) && !/:(batch|free)$/.test(m.id))
  .map((m) => {
    const out = { id: m.id, name: m.name };
    if (typeof m.context_length === "number") out.context_length = m.context_length;
    if (m.pricing) out.pricing = { prompt: m.pricing.prompt, completion: m.pricing.completion };
    if (Array.isArray(m.supported_parameters)) out.supported_parameters = m.supported_parameters.filter((p) => KEPT_PARAMETERS.has(p));
    if (m.architecture) out.architecture = { input_modalities: m.architecture.input_modalities, output_modalities: m.architecture.output_modalities };
    if (typeof m.top_provider?.max_completion_tokens === "number") out.top_provider = { max_completion_tokens: m.top_provider.max_completion_tokens };
    const index = m.benchmarks?.artificial_analysis?.intelligence_index;
    if (typeof index === "number") out.benchmarks = { artificial_analysis: { intelligence_index: index } };
    return out;
  })
  .sort((a, b) => a.id.localeCompare(b.id));

const date = new Date().toISOString().slice(0, 10);
writeFileSync(
  OUT,
  `// Generated by scripts/update-model-knowledge.mjs on ${date} — do not edit by hand.\n` +
    `// OpenRouter's public model list, trimmed: what the picker needs to judge a provider's models.\n` +
    `export const MODEL_SNAPSHOT_DATE = "${date}";\n` +
    `export const MODEL_SNAPSHOT: readonly unknown[] = [\n${models.map((m) => `  ${JSON.stringify(m)},`).join("\n")}\n];\n`,
);
console.log(`model knowledge: ${models.length} models (${PREFIXES.map((p) => `${p.slice(0, -1)} ${models.filter((m) => m.id.startsWith(p)).length}`).join(", ")}) → sidecar/src/model-knowledge.data.ts`);
